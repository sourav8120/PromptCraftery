const fs = require('fs');
const path = require('path');

// Create a simple test image (1x1 pixel PNG)
const pngHeader = Buffer.from([
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
  0x00, 0x00, 0x00, 0x0D, // IHDR chunk length
  0x49, 0x48, 0x44, 0x52, // IHDR
  0x00, 0x00, 0x00, 0x01, // width: 1
  0x00, 0x00, 0x00, 0x01, // height: 1
  0x08, 0x02, 0x00, 0x00, 0x00, // bit depth, color type, etc
  0x90, 0x77, 0x53, 0xDE, // CRC
  0x00, 0x00, 0x00, 0x0C, // IDAT chunk length
  0x49, 0x44, 0x41, 0x54, // IDAT
  0x08, 0x99, 0x01, 0x01, 0x00, 0x00, 0xFE, 0xFF,
  0x00, 0x00, 0x00, 0x02, 0x00, 0x01, // data
  0x4B, 0xB6, 0xEE, 0x56, // CRC
  0x00, 0x00, 0x00, 0x00, // IEND chunk length
  0x49, 0x45, 0x4E, 0x44, // IEND
  0xAE, 0x42, 0x60, 0x82  // CRC
]);

const uploadsDir = path.join(__dirname, 'public', 'uploads', 'prompts');

// Create directory if it doesn't exist
if (!fs.existsSync(uploadsDir)) {
  fs.mkdirSync(uploadsDir, { recursive: true });
  console.log(`Created directory: ${uploadsDir}`);
}

// Write test image
const testImagePath = path.join(uploadsDir, 'test-image.jpg');
fs.writeFileSync(testImagePath, pngHeader);

console.log(`✅ Created test image at: ${testImagePath}`);
console.log(`File size: ${fs.statSync(testImagePath).size} bytes`);
